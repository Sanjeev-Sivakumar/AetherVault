import datetime
import hashlib
import time
from typing import Dict, Any

def query_bank_sfms_cbs(fdr_number: str, ifsc_code: str, account_number: str, principal_amount: float) -> Dict[str, Any]:
    """
    Virtual Open Banking & SFMS (Structured Financial Messaging System) Gateway:
    Simulates direct bank CBS ledger verification conforming to RBI / SFMS financial API standards.
    Clearly distinguishes between Institution Claims and Bank Realities.
    """
    # Deterministic verification simulation
    is_discrepant = fdr_number.startswith("DISC-") or fdr_number.startswith("FAKE-")
    
    # Calculate bank-verified ledger maturity
    tenure_months = 120
    interest_rate = 7.15
    years = tenure_months / 12.0
    verified_maturity_amt = round(principal_amount * ((1.0 + (interest_rate / 400.0)) ** (4.0 * years)), 2)

    return {
        "verified_via": "SFMS_CBS_API",
        "integration_status": "TEST_GATEWAY_AUTHENTICATED",  # Clearly marked as simulated sandbox until bank API VPN configured
        "is_simulated": True,
        "is_configured": True,
        "gateway_node": f"RBI-SFMS-IN-{ifsc_code[:4]}",
        "sfms_reference_id": f"SFMS-2026-IN-{abs(hash(fdr_number)) % 10000000:08d}",
        "bank_status": "ACTIVE_LIEN_CONFIRMED" if not is_discrepant else "INSTRUMENT_DISCREPANCY_FLAGGED",
        "trust_score": 100.0 if not is_discrepant else 25.0,
        "ledger_fdr_number": fdr_number,
        "ledger_account_number": account_number,
        "ledger_principal_amount": principal_amount if not is_discrepant else (principal_amount * 0.5),
        "ledger_maturity_amount": verified_maturity_amt if not is_discrepant else (verified_maturity_amt * 0.5),
        "ledger_interest_rate": interest_rate,
        "ledger_issue_date": "2024-01-15",
        "ledger_maturity_date": "2034-01-15",
        "ledger_lien_marked": not is_discrepant,
        "ledger_lien_favor": "Member Secretary / Regional Officer, AICTE New Delhi",
        "cbs_sync_timestamp": datetime.datetime.now().isoformat(),
        "digital_lien_seal": hashlib.sha256(f"LIEN-SEAL-{fdr_number}-{principal_amount}".encode()).hexdigest()[:24].upper()
    }

def generate_encrypted_financial_token(fdr_number: str, principal_amount: float, bank_code: str = "SBI") -> Dict[str, Any]:
    """
    Encrypted Financial Token (EFT):
    Simulates the Zero-Knowledge sovereign bank token generated by the issuing bank's Core Banking System.
    """
    token_seed = f"EFT-{bank_code}-{fdr_number}-{principal_amount}-{int(time.time())}"
    token_hash = hashlib.sha256(token_seed.encode()).hexdigest()
    
    return {
        "token_id": f"EFT-{bank_code.upper()}-{token_hash[:12].upper()}",
        "cryptographic_signature": token_hash,
        "issuing_bank": bank_code.upper(),
        "lien_status": "IRREVOCABLE_REGULATORY_LIEN",
        "beneficiary": "Member Secretary, AICTE",
        "pki_verified": True,
        "valid_until": "2034-01-15T23:59:59Z"
    }

